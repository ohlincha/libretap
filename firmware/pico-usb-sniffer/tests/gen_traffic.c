// Writes emu_traffic.h for the emulator smoke test: one loop of canned full-speed traffic as the capture PIO would
// push it (usbline.h), and what the filter should make of it.
#include <stdio.h>
#include "usbline.h"

static unsigned words[20000];
static int nwords, packets;

static void push(uint32_t w, void *ctx) { (void)ctx; words[nwords++] = w; if (w & 0x80000000u) packets++; }

static pio_t pio = { .fs = true, .push = push };
static void send(const uint8_t *p, int n) { line_packet(&pio, p, n, false); }
static void tok(int pid, int a, int e) { uint8_t p[3]; pkt_token(p, pid, a, e); send(p, 3); }
static void dat(int pid, const void *d, int n) { uint8_t p[80]; send(p, pkt_data(p, pid, d, n)); }
static void hs(int pid) { uint8_t p[1]; pkt_handshake(p, pid); send(p, 1); }

int main(void)
{
  const int frames = 12, polls = 20;
  line_reset(&pio);
  for (int f = 0; f < frames; f++)
  {
    uint8_t p[3];
    pkt_sof(p, 1000 + f);
    send(p, 3);
    for (int i = 0; i < polls; i++) { tok(9, 5, 1); hs(10); }
    if (f == 3)
    {
      uint8_t setup[8] = { 0x80, 6, 0, 1, 0, 0, 18, 0 };
      uint8_t desc[18] = { 18, 1, 0, 2, 0, 0, 0, 64, 0x03, 0x04, 0x01, 0x60, 0, 6, 1, 2, 3, 1 };
      tok(13, 5, 0); dat(3, setup, 8); hs(2);
      tok(9, 5, 0); dat(11, desc, 18); hs(2);
      tok(1, 5, 0); dat(11, "", 0); hs(2);
    }
    if (f == 7) { tok(1, 5, 2); dat(3, "MEAS?\r", 6); hs(2); }
    if (f == 9) { tok(9, 5, 1); dat(11, "M 0.5123 V\r\n", 12); hs(2); }
  }
  printf("// generated by gen_traffic.c\n#define EMU_FRAMES %d\n#define EMU_KEPT 15\n#define EMU_RESETS 1\n", frames);
  printf("#define EMU_DROPPED %d\n#define EMU_PACKETS %d\n#define EMU_WORDS %d\n", frames + frames * polls * 2, packets, nwords);
  printf("static const uint32_t emu_words[EMU_WORDS] = {\n");
  for (int i = 0; i < nwords; i++)
    printf("0x%08x,%s", words[i], (i % 8 == 7) ? "\n" : " ");
  printf("};\n");
  return 0;
}
