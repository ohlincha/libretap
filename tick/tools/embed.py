"""Write a C file that carries a binary file: embed.py FILE NAME > out.c
(defines NAME[] and NAME_len; used to put libtickhook.so inside tick)."""
import sys

data = open(sys.argv[1], "rb").read()
name = sys.argv[2]
out = ["/* generated by tools/embed.py from %s */" % sys.argv[1].split("/")[-1],
       "const unsigned int %s_len = %d;" % (name, len(data)),
       "const unsigned char %s[] = {" % name]
for i in range(0, len(data), 20):
    out.append("".join("%d," % b for b in data[i:i + 20]))
out.append("};")
sys.stdout.write("\n".join(out) + "\n")
